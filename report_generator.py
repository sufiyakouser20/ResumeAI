
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    HRFlowable
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.units import inch


def generate_pdf_report(
    filename,
    resume_name,
    skills,
    job_results,
    selected_role,
    matched_skills,
    missing_skills
):
    doc = SimpleDocTemplate(
        filename,
        pagesize=A4,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "CustomTitle",
        parent=styles["Title"],
        fontSize=22,
        textColor=colors.HexColor("#273C75"),
        alignment=TA_CENTER,
        spaceAfter=10
    )

    heading_style = ParagraphStyle(
        "CustomHeading",
        parent=styles["Heading2"],
        textColor=colors.HexColor("#5546A5"),
        fontSize=14,
        spaceBefore=15,
        spaceAfter=8
    )

    normal_style = styles["BodyText"]

    elements = []

    # Title
    elements.append(
        Paragraph("RESUME ANALYSIS REPORT", title_style)
    )

    elements.append(
        Paragraph("AI-Powered Career Insights", styles["Italic"])
    )

    elements.append(Spacer(1, 20))

    # Resume information
    elements.append(
        Paragraph("1. Resume Information", heading_style)
    )

    elements.append(
        Paragraph(f"<b>Resume File:</b> {resume_name}", normal_style)
    )

    elements.append(
        Paragraph(f"<b>Total Skills Identified:</b> {len(skills)}", normal_style)
    )

    elements.append(Spacer(1, 12))

    # Skills
    elements.append(
        Paragraph("2. Extracted Skills", heading_style)
    )

    elements.append(
        Paragraph(", ".join(skills) if skills else "No skills identified.", normal_style)
    )

    elements.append(Spacer(1, 12))

    # Job recommendations
    elements.append(
        Paragraph("3. Job Recommendations", heading_style)
    )

    table_data = [
        ["Job Role", "Match Score"]
    ]

    for _, row in job_results.iterrows():
        table_data.append([
            str(row["role"]),
            f'{float(row["match_score"]):.2f}%'
        ])

    job_table = Table(
        table_data,
        colWidths=[4 * inch, 1.5 * inch]
    )

    job_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#273C75")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("PADDING", (0, 0), (-1, -1), 8),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1),
         [colors.whitesmoke, colors.lightgrey]),
    ]))

    elements.append(job_table)

    elements.append(Spacer(1, 12))

    # Selected career role
    elements.append(
        Paragraph("4. Selected Career Role", heading_style)
    )

    elements.append(
        Paragraph(str(selected_role), normal_style)
    )

    # Matched skills
    elements.append(
        Paragraph("5. Skills You Already Have", heading_style)
    )

    elements.append(
        Paragraph(
            ", ".join(matched_skills) if matched_skills else "No matching skills found.",
            normal_style
        )
    )

    # Missing skills
    elements.append(
        Paragraph("6. Skills to Improve", heading_style)
    )

    elements.append(
        Paragraph(
            ", ".join(missing_skills) if missing_skills else "No major skill gaps identified.",
            normal_style
        )
    )

    elements.append(Spacer(1, 25))

    elements.append(HRFlowable(
        width="100%",
        thickness=1,
        color=colors.HexColor("#5546A5")
    ))

    elements.append(Spacer(1, 8))

    elements.append(
        Paragraph(
            "Generated by ResumeAI | This report provides estimated career matches, "
            "not a guarantee of employment.",
            styles["Italic"]
        )
    )

    doc.build(elements)

    return filename
